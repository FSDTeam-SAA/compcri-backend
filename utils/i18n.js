const dateLocales = { en: 'en-US', pt: 'pt-BR', es: 'es' };

/// [text] in [locale], with `{name}` placeholders filled from [args]. A
/// function argument receives the locale, for values that are themselves
/// language-dependent (dates). Unknown text is returned as written.
export const translate = (locale, text, args = {}) => {
  if (typeof text !== 'string') return text;
  let result = messages[locale]?.[text] || text;
  for (const [key, value] of Object.entries(args)) {
    result = result.replaceAll(`{${key}}`, typeof value === 'function' ? value(locale) : String(value));
  }
  return result;
};

/// The language to answer a request in: the app sends the one it is showing,
/// otherwise the signed-in user's profile language, otherwise English.
export const requestLocale = (req) => {
  for (const part of String(req.headers?.['accept-language'] || '').split(',')) {
    const code = part.trim().slice(0, 2).toLowerCase();
    if (LOCALES.includes(code)) return code;
  }
  return LOCALES.includes(req.user?.locale) ? req.user.locale : 'en';
};

/// A date and time the way people in [locale] write it, in [timeZone].
export const formatDateTime = (locale, date, timeZone = 'UTC') => {
  const options = { dateStyle: 'medium', timeStyle: 'short' };
  try {
    return new Intl.DateTimeFormat(dateLocales[locale] || 'en-US', { ...options, timeZone }).format(date);
  } catch {
    return new Intl.DateTimeFormat(dateLocales[locale] || 'en-US', { ...options, timeZone: 'UTC' }).format(date);
  }
};

